# WRITE A program to accept person's height
#       Display "Tall person" if the height is greater than 6 
#       otherwise "Not a tall person"

height = int(input("Please enter persons height"))
if ( height > 6 ):
    print ("Tall person")
    
if (height <= 6):
    print ("Not a tall person")
    
